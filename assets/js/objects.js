//TODO: Объекты (Objects)
/**
 *! Объекты – это ассоциативные массивы с рядом дополнительных возможностей.
 *? Они хранят свойства (пары ключ-значение), где:
 ** Ключи свойств должны быть строками или символами (специальный тип для идентификаторов).
 ** Значения могут быть любого типа.
 ** Для объектов ограничения на имена свойств - НЕТ
 ** Все другие типы данных будут автоматически преобразованы к строке.
 *! В JS можно получить доступ к любому свойству.
 *! Даже если свойства не существует – возвращается undefined!

 *? Чтобы получить доступ к свойству, мы можем использовать:
 ** Запись через точку:
 * obj.property.
 ** Квадратные скобки:
 * obj["property"]:
 ** ** позволяют взять ключ из переменной:
 * obj[varWithKey]

 *? Дополнительные операторы:
 ** Удаление свойства:
 * delete obj.prop
 ** Проверка существования свойства:
 * "key" in obj
 ** Перебор свойств объекта: цикл for
 for (let key in obj).

 *? В JavaScript есть много других типов объектов:
 ** Array для хранения упорядоченных коллекций данных,
 ** Date для хранения информации о дате и времени,
 ** Error для хранения информации об ошибке.
 ** … и так далее.
 */

// Объект может быть создан с помощью фигурных скобок {…}
// с необязательным списком свойств.
let user1 = new Object(); // синтаксис "конструктор объекта"
let user2 = {};  // "литерал объекта" или "литеральная нотация"

//TODO: Литералы и свойства
/**
 * При использовании литерального синтаксиса {...}
 * мы сразу можем поместить в объект несколько свойств
 * в виде пар «ключ: значение»
 * перечисляются через запятую.
 * свойство: значение,
 * Имя свойства может состоять из нескольких слов, но в кавычках
 * Значение может быть любого типа
 * Последнее свойство объекта может заканчиваться запятой («висячая запятая»)

 *! Объект, объявленный как константа, может быть изменён
 ** объявление const защищает от изменений только саму переменную user,
 ** а не её содержимое.

 ** Мы можем использовать квадратные скобки в литеральной нотации
 ** для создания вычисляемого свойства.
 */
let user = {     // объект
  name: "John",  // под ключом "name" хранится значение "John"
  age: 30        // под ключом "age" хранится значение 30
};

// получаем свойства объекта через точку:
alert( user.name ); // John
alert( user.age ); // 30

// Значение может быть любого типа
user.isAdmin = true;

// Удаление свойства
delete user.age;

// Имя свойства может состоять из нескольких слов
let user = {
  name: "John",
  age: 30,
  "likes birds": true  // имя свойства из нескольких слов должно быть в кавычках
};

// Последнее свойство объекта может заканчиваться запятой:
let user = {
  name: "John",
  age: 30,
}

// Объект, объявленный через const, может быть изменён.
const user = {
  name: "John"
};

user.name = "Pete"; // (*)

alert(user.name); // Pete

// доступ к свойствам через квадратные скобки
let user = {};

// присваивание значения свойству
user["likes birds"] = true;

// получение значения свойства
alert(user["likes birds"]); // true

// удаление свойства
delete user["likes birds"];

// имя свойства может храниться в переменной:
let key = "likes birds";
// то же самое, что и user["likes birds"] = true;
user[key] = true;


// квадратные скобки в литеральной нотации для создания вычисляемого свойства.
let fruit = prompt("Какой фрукт купить?", "apple");
let bag = {
  [fruit]: 5, // имя свойства будет взято из переменной fruit
};
alert( bag.apple ); // 5, если fruit="apple"


// можем использовать и более сложные выражения
fruit = 'apple';
bag = {
  [fruit + 'Computers']: 5 // bag.appleComputers = 5
};

