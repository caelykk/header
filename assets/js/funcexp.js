/**
 * Существует ещё один синтаксис создания функций
 * Function Expression (Функциональное Выражение)
 * позволяет нам создавать новую функцию в середине любого выражения.

 * Функция – это значение => мы можем обращаться с ней как со значением
 */
let sayHi = function() {
  alert( "Привет" );
};

// Мы можем скопировать функцию в другую переменную:
function sayHi() {   // (1) создаём
  alert( "Привет" );
}

let func = sayHi;    // (2) копируем

func(); // Привет     // (3) вызываем копию (работает)!
sayHi(); // Привет    //     эта тоже все ещё работает (почему бы и нет)


