//TODO: Функции-«колбэки»
/**
 * (от англ. «call back» – обратный вызов)
 * Это функция, которую мы передаём как аргумент в другую функцию
 * и ожидаем, что она вызовется обратно когда-нибудь позже,
 * если это будет необходимо.
 * 
 */
function ask(question, yes, no) {
  if (confirm(question)) yes()
  else no();
}

function showOk() {
  alert( "Вы согласны." );
}

function showCancel() {
  alert( "Вы отменили выполнение." );
}

// использование: функции showOk, showCancel передаются в качестве аргументов ask
ask("Вы согласны?", showOk, showCancel);
// Аргументы showOk и showCancel функции ask называются функциями-колбэками
// или просто колбэками.

//TODO: Function Expression в сравнении с Function Declaration
/**
 * Ключевые отличия Function Declaration от Function Expression:
 1)
    *? Function Declaration:
    функция объявляется отдельной конструкцией «function…» в основном потоке кода.
    ** Function Expression:
    функция, созданная внутри другого выражения или синтаксической конструкции.
 2)
    *? Function Declaration:
    может быть вызвана раньше, чем она объявлена.
    ** Function Expression:
    создаётся, когда выполнение доходит до него, и затем уже может использоваться.
 3)
    *? В строгом режиме, когда Function Declaration находится в блоке {...},
    функция доступна везде внутри блока. Но не снаружи него.
    ** Для решения проблемы нужно воспользоваться Function Expression
 */

// Так будет работать
sayHi("Вася"); // Привет, Вася

function sayHi(name) {
  alert( `Привет, ${name}` );
}

// а так будет ошибка
sayHi("Вася"); // ошибка!

let sayHi = function(name) {  // (*) магии больше нет
  alert( `Привет, ${name}` );
};

let age = 16; // возьмём для примера 16

if (age < 18) {
  welcome();               // \   (выполнится)
                           //  |
  function welcome() {     //  |
    alert("Привет!");      //  |  Function Declaration доступно
  }                        //  |  во всём блоке кода, в котором объявлено
                           //  |
  welcome();               // /   (выполнится)

} else {

  function welcome() {
    alert("Здравствуйте!");
  }
}

// здесь фигурная скобка закрывается,
// поэтому Function Declaration, созданные внутри блока кода выше -- недоступны отсюда.

