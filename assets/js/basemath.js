// Базовые операторы

/**
 * Операнд – то, к чему применяется оператор.
 * Унарный оператор - оператор, который применяется к одному операнду.
 * Бинарный оперетор - оператор, который применяется к двум операндам.
*/

let x = 1;
x = -x;
alert( x ); // -1, применили унарный минус

let y = 1, z = 3;
alert( z - y ); // 2, бинарный минус вычитает значения

