// Инкремент/декремент
/**
 * Инкремент ++ увеличивает переменную на 1
 * Декремент -- уменьшает переменную на 1
 * Можно применить только к переменной.
 * Могут также использоваться внутри выражений.
 * Приоритет выше, чем у большинства других арифметических операций.

 Префиксная форма:
 * ++counter - сначала увеличивает, затем возвращает
 * --counter - сначала уменьшает, затем возвращает

 Постфиксная форма:
 * counter++ - сначала вернет, потом увеличит
 * counter-- - сначала вернет, потом уменьшит

 Что использовать:
 * Любой - Если результат не используется,
           а нужно только увеличить/уменьшить
 * Префиксная - если результат тут же используется
 * Постфиксная - если нужно значение, до увеличения/уменьшения
*/

let counter = 1;
let p = ++counter; // Префиксный инкремент
let q = --counter; // Префиксный декремент
alert(p, q); // 2, 0

counter = 1;
let l = counter++; // Постфиксный инкремент
let k = counter--; // Постфиксный декремент

alert(l, k); // 1, 1


